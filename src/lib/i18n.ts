import {
  createContext,
  createElement,
  useCallback,
  useContext,
  useEffect,
  useMemo,
  useState,
  type ReactNode,
} from "react";

export type Locale = "ko" | "en";

const STORAGE_KEY = "abliterater_locale";
const EVENT = "abliterater-locale-change";

type I18nSingleton = {
  currentLocale: Locale;
  listeners: Set<(loc: Locale) => void>;
};

declare global {
  interface Window {
    __ABLITERATER_I18N__?: I18nSingleton;
  }
}

const ssrBag: I18nSingleton = {
  currentLocale: "ko",
  listeners: new Set<(loc: Locale) => void>(),
};

function getI18nSingleton(): I18nSingleton {
  if (typeof window === "undefined") return ssrBag;
  const w = window as Window & { __ABLITERATER_I18N__?: I18nSingleton };
  if (!w.__ABLITERATER_I18N__) {
    w.__ABLITERATER_I18N__ = {
      currentLocale: "ko",
      listeners: new Set<(loc: Locale) => void>(),
    };
  }
  return w.__ABLITERATER_I18N__;
}

function readStoredLocale(): Locale {
  if (typeof window === "undefined") return "ko";
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "ko" || saved === "en") return saved;
  } catch {
    // ignore
  }
  return "ko";
}

export function getLocale(): Locale {
  return getI18nSingleton().currentLocale;
}

export function setLocale(locale: Locale): boolean {
  const bag = getI18nSingleton();
  const changed = bag.currentLocale !== locale;
  bag.currentLocale = locale;
  let stored = false;
  if (typeof window !== "undefined") {
    try {
      localStorage.setItem(STORAGE_KEY, locale);
      stored = localStorage.getItem(STORAGE_KEY) === locale;
    } catch {
      stored = false;
    }
    document.documentElement.lang = locale;
    try {
      window.dispatchEvent(new CustomEvent(EVENT, { detail: locale }));
    } catch {
      // ignore
    }
  }
  bag.listeners.forEach((fn) => fn(locale));
  return stored || changed;
}

type LocaleContextValue = [Locale, (loc: Locale) => void];

const LocaleContext = createContext<LocaleContextValue | null>(null);

export function LocaleProvider({ children }: { children: ReactNode }) {
  // First paint always "ko" to match SSR HTML; apply storage after hydrate.
  const [locale, setLocal] = useState<Locale>("ko");

  useEffect(() => {
    const bag = getI18nSingleton();
    const handler = (l: Locale) => setLocal(l);
    bag.listeners.add(handler);
    const onWin = (ev: Event) => {
      const detail = (ev as CustomEvent<Locale>).detail;
      if (detail === "ko" || detail === "en") setLocal(detail);
    };
    window.addEventListener(EVENT, onWin as EventListener);
    const stored = readStoredLocale();
    if (stored !== bag.currentLocale || stored !== locale) {
      setLocale(stored);
      setLocal(stored);
    } else {
      setLocal(stored);
      document.documentElement.lang = stored;
    }
    return () => {
      bag.listeners.delete(handler);
      window.removeEventListener(EVENT, onWin as EventListener);
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps -- mount-only hydrate sync
  }, []);

  const update = useCallback((loc: Locale) => {
    setLocale(loc);
    setLocal(loc);
  }, []);

  const value = useMemo<LocaleContextValue>(() => [locale, update], [locale, update]);
  return createElement(LocaleContext.Provider, { value }, children);
}

export function useLocale(): LocaleContextValue {
  const ctx = useContext(LocaleContext);
  const [locale, setLocal] = useState<Locale>("ko");

  useEffect(() => {
    if (ctx) return;
    const bag = getI18nSingleton();
    const handler = (l: Locale) => setLocal(l);
    bag.listeners.add(handler);
    const onWin = (ev: Event) => {
      const detail = (ev as CustomEvent<Locale>).detail;
      if (detail === "ko" || detail === "en") setLocal(detail);
    };
    window.addEventListener(EVENT, onWin as EventListener);
    setLocal(getLocale());
    return () => {
      bag.listeners.delete(handler);
      window.removeEventListener(EVENT, onWin as EventListener);
    };
  }, [ctx]);

  const update = useCallback((loc: Locale) => {
    setLocale(loc);
    setLocal(loc);
  }, []);

  if (ctx) return ctx;
  return [locale, update];
}

